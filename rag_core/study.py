"""Study Companion workflow built on the shared pipeline.

Small matches are expanded to their parent section within a word budget, one
follow-up carries the earlier *question* (never an earlier answer) into a new
retrieval, and the offline explanation is verbatim sentences, not generated text."""
from dataclasses import asdict
from hashlib import sha256
from time import perf_counter
import re
from .core import Chunk, tokens

FOLLOWUP_PREFIXES = ('what about', 'and ', 'how about', 'why is that', 'what if', 'does it', 'does that',
                     'is it', 'is that', 'how does it', 'how does that', 'can it', 'why does it')
QUALIFIER = re.compile(r'\b(except|exception|unless|not|only if|however|but|cannot)\b', re.I)
SENTENCE = re.compile(r'(?<=[.!?])\s+')
EXTRACTIVE_LABEL = ('Source-search mode — verbatim sentences from the supporting sections, ranked by keyword overlap '
                    'with a small boost for qualifiers (not, unless, except, however, but). Not a generated explanation.')
GENERATED_LABEL = ('Generated by the configured model from the supporting sections below. Citation IDs were validated; '
                   'check each claim against the sections yourself.')


def words(text):
    return len(text.split())


def is_followup(question):
    return question.strip().lower().startswith(FOLLOWUP_PREFIXES)


def build_context(chunks, documents, budget, expand_below, expand=True):
    """Turn ranked chunks into context items, expanding small partial matches to
    their parent section while the total stays within ``budget`` words.

    The top-ranked match is always kept (unexpanded) even if it alone exceeds the
    budget, so a long section never produces empty evidence; ``over_budget`` flags it."""
    sections = {(d['id'], s['id']): (d, s) for d in documents for s in d['sections']}
    context, skipped, used, by_section = [], [], 0, {}
    for c in chunks:
        doc, section = sections[(c.doc_id, c.metadata['section'])]
        key = (c.doc_id, section['id'])
        if key in by_section:  # the whole parent section is already in context
            by_section[key]['matched_chunk_ids'].append(c.id)
            continue
        partial = c.text != section['text']
        if expand and partial and words(c.text) < expand_below:
            if used + words(section['text']) <= budget:
                item = _item(c, doc, section, expanded=True)
                by_section[key] = item
                context.append(item)
                used += item['words']
                continue
            skipped.append({'chunk_id': c.id, 'reason': 'parent section would exceed the context budget'})
        if context and used + words(c.text) > budget:
            skipped.append({'chunk_id': c.id, 'reason': 'chunk would exceed the context budget'})
            continue
        item = _item(c, doc, section, expanded=False)
        if not partial:
            by_section[key] = item
        context.append(item)
        used += item['words']
    return context, {'budget_words': budget, 'used_words': used, 'over_budget': used > budget,
                     'expand_below_words': expand_below, 'expansion_enabled': expand, 'skipped': skipped}


def _item(chunk, doc, section, expanded):
    text = section['text'] if expanded else chunk.text
    return {'id': f"{doc['id']}:{section['id']}" if expanded else chunk.id, 'doc_id': doc['id'],
            'section_id': section['id'], 'title': section['title'], 'location': chunk.location, 'text': text,
            'words': words(text), 'expanded': expanded, 'matched_chunk_ids': [chunk.id],
            'metadata': {**chunk.metadata, 'content_hash': sha256(text.encode()).hexdigest()}}


def as_chunk(item):
    return Chunk(item['id'], item['doc_id'], item['title'], item['text'], item['location'],
                 {**item['metadata'], 'expanded_from': list(item['matched_chunk_ids'])} if item['expanded'] else item['metadata'])


def extract(question, context, limit=4):
    """Pick up to ``limit`` verbatim sentences, returned in reading order."""
    terms = set(tokens(question))
    candidates = []
    for pos, item in enumerate(context):
        for i, sentence in enumerate(s for s in SENTENCE.split(item['text']) if s.strip()):
            overlap = len(terms & set(tokens(sentence)))
            if overlap:
                score = overlap + (1 if QUALIFIER.search(sentence) else 0)
                candidates.append((-score, pos, i, sentence, item['id']))
    chosen = sorted(sorted(candidates)[:limit], key=lambda c: (c[1], c[2]))
    return [{'text': s, 'source_id': source} for _, _, _, s, source in chosen]


class StudyCompanion:
    def __init__(self, pipeline):
        self.pipe = pipeline
        settings = pipeline.config.get('study', {})
        self.budget = int(settings.get('context_budget_words', 250))
        self.expand_below = int(settings.get('expand_below_words', 60))
        self.k = int(settings.get('k', 4))
        if self.budget < 1 or self.expand_below < 1 or not 1 <= self.k <= 50:
            raise ValueError('Invalid study settings')

    @property
    def chunk_mode(self):
        return self.pipe.chunk_mode

    def ingest(self, chunk_mode='section'):
        self.pipe.ingest(chunk_mode)

    def original_section(self, doc_id, section_id):
        for doc in self.pipe.documents:
            for section in doc['sections']:
                if doc['id'] == doc_id and section['id'] == section_id:
                    return {'doc_title': doc['title'], 'version': doc.get('version', '1'), **section}
        raise KeyError(f'{doc_id}:{section_id}')

    def ask(self, question, conversation=None, mode='keyword', expand=True):
        """``conversation`` holds only the topic question and follow-up count;
        any other keys (such as an earlier answer) are ignored."""
        if not question.strip() or len(question) > 4000:
            raise ValueError('Question must contain 1–4000 characters')
        topic = (conversation or {}).get('topic_question')
        used = (conversation or {}).get('followups_used', 0)
        current = {'topic_question': topic, 'followups_used': used} if topic else {}
        base = {'original_question': question, 'chunk_mode': self.chunk_mode, 'retrieval_mode': mode,
                'sources': [], 'retrieved': [], 'context': [], 'explanation': None}
        if is_followup(question):
            if not topic:
                return {**base, 'status': 'clarification', 'conversation': current,
                        'notice': 'This looks like a follow-up. Name the topic or ask an initial question first.'}
            if used >= 1:
                return {**base, 'status': 'clarification', 'conversation': current,
                        'notice': 'This topic already used its one follow-up. Ask a complete question or reset the conversation.'}
            query = topic + '\nFollow-up: ' + question
            conversation = {'topic_question': topic, 'followups_used': 1}
        else:
            query = question
            conversation = {'topic_question': question, 'followups_used': 0}
        started = perf_counter()
        retrieved = self.pipe.retrieve(query, mode=mode, k=self.k)
        context, budget = build_context(retrieved, self.pipe.documents, self.budget, self.expand_below, expand)
        ready = perf_counter()
        result = self.pipe.respond(query, [as_chunk(i) for i in context])
        if result['status'] == 'generated':
            explanation = {'kind': 'generated', 'label': GENERATED_LABEL, 'text': result['answer']}
        elif context:
            explanation = {'kind': 'extractive', 'label': EXTRACTIVE_LABEL, 'sentences': extract(query, context)}
        else:
            explanation = None
        result.update(base, sources=result['sources'], retrieved=[asdict(c) for c in retrieved], context=context,
                      context_budget=budget, explanation=explanation, retrieval_query=query, conversation=conversation,
                      timings_ms={'retrieval': (ready - started) * 1000, 'generation': (perf_counter() - ready) * 1000})
        return result
